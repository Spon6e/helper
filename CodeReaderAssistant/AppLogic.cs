    public static AssistantResult Translate(string text)
    {
        var value = text.Trim();
        if (value.Length == 0)
        {
            return new AssistantResult(
                "Выделение пустое. Выделите английский текст и нажмите Ctrl+Shift+Space.",
                string.Empty);
        }

        var singleWord = Regex.Match(value, @"^[A-Za-z_][A-Za-z0-9_]*$");
        if (singleWord.Success)
        {
            var word = singleWord.Value;
            var translatedWord = TranslateIdentifier(word);
            return new AssistantResult(
                translatedWord != word
                    ? $"{word}  →  {translatedWord}"
                    : $"{word}  →  нет в локальном словаре",
                string.Empty);
        }

        var result = value;
        foreach (var phrase in RussianWords.Where(item => item.Key.Contains(' ')).OrderByDescending(item => item.Key.Length))
        {
            result = Regex.Replace(result, $@"\b{Regex.Escape(phrase.Key)}\b", phrase.Value, RegexOptions.IgnoreCase);
        }

        result = Regex.Replace(result, @"[A-Za-z_][A-Za-z0-9_]*(?:'[A-Za-z]+)?", match =>
        {
            return TranslateIdentifier(match.Value);
        });

        return new AssistantResult("Перевод:\r\n" + result, string.Empty);
    }

    private static string TranslateIdentifier(string identifier)
    {
        if (RussianWords.TryGetValue(identifier, out var directTranslation))
        {
            return PreserveCase(identifier, directTranslation);
        }

        if (identifier.StartsWith("__", StringComparison.Ordinal)
            && identifier.EndsWith("__", StringComparison.Ordinal))
        {
            return identifier;
        }

        var spaced = Regex.Replace(identifier, @"([A-Z]+)([A-Z][a-z])", "$1 $2");
        spaced = Regex.Replace(spaced, @"([a-z0-9])([A-Z])", "$1 $2");
        var parts = spaced.Split('_', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .SelectMany(part => part.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            .ToArray();

        if (parts.Length < 2)
        {
            return identifier;
        }

        var translatedParts = parts.Select(part =>
            RussianWords.TryGetValue(part, out var translation) ? translation : part).ToArray();
        var changed = translatedParts.Where((part, index) => part != parts[index]).Any();
        return changed
            ? string.Join(" ", translatedParts)
            : identifier;
    }

    private static string PreserveCase(string source, string translated)
    {
        if (source.Length > 0 && char.IsUpper(source[0]))
        {
            return char.ToUpper(translated[0]) + translated[1..];
        }

        return translated;
    }

    private static string BuildStructureSummary(string text, ProgrammingLanguage language)
    {
        var parts = new List<string>();
        if (language == ProgrammingLanguage.Python)
        {
            if (Regex.IsMatch(text, @"\bdef\s+\w+\s*\(")) parts.Add("объявляет функцию");
            if (Regex.IsMatch(text, @"\bclass\s+\w+")) parts.Add("объявляет класс");
            if (Regex.IsMatch(text, @"\b(for|while)\b")) parts.Add("содержит цикл");
            if (Regex.IsMatch(text, @"\b(if|elif|else)\b")) parts.Add("содержит условную ветку");
            if (Regex.IsMatch(text, @"\b(import|from)\b")) parts.Add("подключает модуль");
            if (Regex.IsMatch(text, @"\b(try|except|finally)\b")) parts.Add("обрабатывает исключения");
            if (Regex.IsMatch(text, @"\b(return|yield)\b")) parts.Add("возвращает результат или промежуточные значения");
            if (Regex.IsMatch(text, @"\[.*\bfor\b.*\]", RegexOptions.Singleline)) parts.Add("создаёт списковое включение");
            if (Regex.IsMatch(text, @"\bwith\b")) parts.Add("использует контекстный менеджер");
            if (Regex.IsMatch(text, @"\b(match|case)\b")) parts.Add("сопоставляет значение с вариантами");
            if (Regex.IsMatch(text, @"\braise\b")) parts.Add("выбрасывает исключение");
            if (Regex.IsMatch(text, @"\blambda\b")) parts.Add("создаёт анонимную функцию");
            if (Regex.IsMatch(text, @"^\s*@\w+", RegexOptions.Multiline)) parts.Add("использует декоратор");
        }
        else
        {
            if (Regex.IsMatch(text, @"#\s*include")) parts.Add("подключает заголовочный файл");
            if (Regex.IsMatch(text, @"#\s*define")) parts.Add("создаёт макрос препроцессора");
            if (Regex.IsMatch(text, @"\b(class|struct)\s+\w+")) parts.Add("объявляет пользовательский тип");
            if (Regex.IsMatch(text, @"\b(for|while|do)\b")) parts.Add("содержит цикл");
            if (Regex.IsMatch(text, @"\b(if|else|switch|case)\b")) parts.Add("содержит условный выбор");
            if (Regex.IsMatch(text, @"\b(try|catch|throw)\b")) parts.Add("использует исключения");
            if (Regex.IsMatch(text, @"\b(std::|vector|string|map|set|array|optional|variant|ranges|filesystem)\b")) parts.Add("использует элементы стандартной библиотеки");
            if (Regex.IsMatch(text, @"\b(thread|jthread|mutex|atomic|future|async)\b")) parts.Add("использует многопоточность или асинхронную операцию");
            if (Regex.IsMatch(text, @"\b(sort|find|transform|accumulate|lower_bound)\b")) parts.Add("использует алгоритм стандартной библиотеки");
            if (Regex.IsMatch(text, @"\b(main)\s*\(")) parts.Add("содержит точку входа программы");
            if (Regex.IsMatch(text, @"\b(return)\b")) parts.Add("возвращает значение из функции");
            if (Regex.IsMatch(text, @"\b(namespace|using)\b")) parts.Add("работает с пространством имён или псевдонимом");
            if (Regex.IsMatch(text, @"\b(template|concept|requires)\b")) parts.Add("использует обобщённое программирование");
            if (Regex.IsMatch(text, @"\b(enum|union)\b")) parts.Add("объявляет специальный пользовательский тип");
            if (Regex.IsMatch(text, @"\b(virtual|override)\b")) parts.Add("использует полиморфизм");
            if (Regex.IsMatch(text, @"\b(constexpr|consteval)\b")) parts.Add("вычисляет часть кода на этапе компиляции");
        }

        if (Regex.IsMatch(text, @"//|#(?!include)") || text.Contains("\"\"\"") || text.Contains("'''"))
        {
            parts.Add("содержит комментарий или документирующую строку");
        }
        return parts.Count > 0 ? "Фрагмент " + string.Join(", ", parts) + "." : "структура фрагмента требует более подробного контекста.";
    }

    private static List<string> BuildSyntaxHints(string text, ProgrammingLanguage language)
    {
        var hints = new List<string>();
        if (Regex.IsMatch(text, @"(?<![=!<>])=(?!=)")) hints.Add("есть присваивание значения");
        if (Regex.IsMatch(text, @"==|!=|<=|>=|<|>")) hints.Add("есть сравнение значений");
        if (Regex.IsMatch(text, @"\b(and|or|not)\b|&&|\|\||!")) hints.Add("используется логическая операция");
        if (Regex.IsMatch(text, @"\+\+|--|\+=|-=|\*=|/=|\+|-|\*|/")) hints.Add("используется арифметическая или составная операция");
        if (Regex.IsMatch(text, @"\b\w+\s*\(")) hints.Add("вызывается функция или метод");
        if (language == ProgrammingLanguage.Cpp && Regex.IsMatch(text, @"::|->|\*\s*\w+|\w+\s*&")) hints.Add("используется обращение к пространству имён, члену, указателю или ссылке");
        if (language == ProgrammingLanguage.Cpp && Regex.IsMatch(text, @"<<|>>")) hints.Add("используется потоковый ввод или вывод");
        if (language == ProgrammingLanguage.Cpp && Regex.IsMatch(text, @"\[[^\]]*\]\s*\(")) hints.Add("используется lambda-выражение");
        if (language == ProgrammingLanguage.Cpp && Regex.IsMatch(text, @"\btemplate\b|\bconcept\b|\brequires\b")) hints.Add("используются шаблоны или ограничения типов");
        if (language == ProgrammingLanguage.Cpp && Regex.IsMatch(text, @"\b(std::move|std::forward)\b")) hints.Add("используется семантика перемещения");
        if (language == ProgrammingLanguage.Python && Regex.IsMatch(text, @"\b\w+\s*\[.*\]")) hints.Add("обращение к элементу по индексу или ключу");
        if (language == ProgrammingLanguage.Python && Regex.IsMatch(text, @"\*\w+|\*\*\w+")) hints.Add("распаковываются аргументы функции");
        if (language == ProgrammingLanguage.Python && Regex.IsMatch(text, @"f[""']")) hints.Add("используется форматированная строка");
        return hints;
    }
